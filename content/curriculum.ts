/**
 * The whole TururuCoding curriculum: tracks, units, lessons, unit projects and capstones.
 *
 * This file is the map. A unit with `ready: true` has its lessons written in
 * content/units/<folder>/. Every other unit is planned: the titles are fixed here
 * so you can see the full road, and the lessons get written unit by unit.
 *
 * Lesson ids are made from the unit id and the position: "html-01", "html-02", ...
 * The unit's skip check is "<unit>-check" and its project is "<unit>-project".
 */

export type RunsIn = "site" | "computer" | "both";

export interface UnitSpec {
  id: string;
  title: string;
  /** One sentence: what this unit is about. */
  summary: string;
  /** "After this unit you can ..." */
  outcomes: string[];
  /** Where you write the code for these lessons. */
  runsIn: RunsIn;
  lessons: string[];
  project: { title: string; summary: string };
  ready?: boolean;
  /** Folder under content/units/ when the unit is written. */
  folder?: string;
}

export interface TrackSpec {
  id: string;
  title: string;
  summary: string;
  /** Why this track is in your curriculum. */
  why: string;
  /** What you should finish first. */
  startAfter: string;
  units: UnitSpec[];
  capstone: { title: string; summary: string; youBuild: string[] };
}

